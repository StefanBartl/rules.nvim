---@module 'rules.engine.catalog'
---@brief Build the reading documents ("catalogs") of a ruleset from its layouts and rule files.
---@description
--- A ruleset in the one-file-per-rule form has no document a person reads top
--- to bottom: the rules are files, and the documents are **generated**, like
--- `TASKS.md` of tasks.nvim. A *layout* says what a document is made of; the
--- generator puts it together and writes it, or with `check` only says whether
--- the file on disk is up to date (for CI).
---
--- A layout is a Markdown file whose frontmatter says `kind: layout` and
--- `output: <path of the document, relative to the ruleset root>`. Its body is
--- the document as it should read, with two kinds of lines taken for tokens:
---
---     {{rule DEP-06}}   replaced by the rule, as it reads in the document
---     {{toc}}           replaced by the table of contents of the finished document
---
--- Everything else (headings, introductions, separators) is copied as it is.
--- The order of the rules is the order of the tokens; the rule files carry no
--- order. A rule reads in the document as: its heading and the text under it,
--- and a ```rule block with `id` and `severity` put back in (the file holds them
--- in the frontmatter only; see `parser.read_rule_file`).
---
--- The output starts with a header line (`<!-- GENERATED by rules.nvim ... -->`).
--- The loader skips a file that starts with it, so a catalog and the rule files
--- it was made from never load as duplicates.
---
--- Pure: `render` takes the layout and a lookup for rule files and returns
--- text, `build` is the one function that touches the disk.

local parser = require("rules.engine.parser")
local frontmatter = require("lib.nvim.markdown.frontmatter")
local fswalk = require("rules.engine.fswalk")
local loader = require("rules.engine.loader")
local expand_path = require("lib.nvim.cross.fs.expand_path")

local M = {}

M.TOC_TOKEN = "{{toc}}"

--- The heading above the table of contents is not listed in it.
local TOC_HEADING = "table of content"

-- ── table of contents ────────────────────────────────────────────────────────

--- The anchor of a heading. The hand-kept tables of contents of the existing
--- rulesets spell it in two ways, which `params` chooses between:
---   * `unicode = 0` (default): lower case, anything but ASCII letters, digits, `-`
---     and spaces dropped (an umlaut goes, it does not become `u`), runs of spaces
---     and hyphens one hyphen; `_` stays with `underscore = 1` (default), goes with 0;
---   * `unicode = 1`: the renderers' way: lower case, letters of any alphabet,
---     digits, `-` and `_` stay, punctuation goes, every space is a hyphen (a
---     dropped dash between two spaces leaves `--`).
---@param text string
---@param params? Rules.TocParams
---@return string
function M.slug(text, params)
  params = params or M.TOC_DEFAULTS
  if params.unicode == 1 then
    local out = {}
    for _, ch in ipairs(vim.fn.split(text, "\\zs")) do
      if #ch == 1 then
        if ch:match("[%w_%-]") then
          out[#out + 1] = ch:lower()
        elseif ch == " " then
          out[#out + 1] = "-"
        end
      else
        local lower, upper = vim.fn.tolower(ch), vim.fn.toupper(ch)
        if lower ~= upper then
          out[#out + 1] = lower
        end
      end
    end
    return table.concat(out)
  end
  local keep = params.underscore == 1 and "[^%w_%- ]" or "[^%w%- ]"
  local s = text:lower():gsub(keep, "")
  s = s:gsub("[ %-]+", "-")
  s = s:gsub("^%-", ""):gsub("%-$", "")
  return s
end

--- The headings of a document, outside fenced code.
---@param lines string[]
---@return {level: integer, text: string}[]
local function headings(lines)
  local out = {}
  local fence = 0
  for _, line in ipairs(lines) do
    if fence > 0 then
      local ticks = line:match("^(`+)%s*$")
      if ticks and #ticks >= fence then
        fence = 0
      end
    elseif line:match("^```") then
      fence = #line:match("^(`+)")
    else
      local hashes, text = line:match("^(#+)%s+(.-)%s*$")
      if hashes and #hashes <= 6 then
        out[#out + 1] = { level = #hashes, text = text }
      end
    end
  end
  return out
end

---@class Rules.TocParams
---@field max integer  the deepest heading level listed (2 to 6)
---@field base integer  indentation, in spaces, of the first level (level 2)
---@field step integer  further indentation, in spaces, per level
---@field unicode integer  1: anchors keep letters of any alphabet (see `slug`)
---@field underscore integer  0: an anchor drops `_` (only with `unicode = 0`)

--- What `{{toc}}` means without parameters: levels 2 to 4, level 2 indented by two
--- spaces and two more per level, ASCII anchors that keep `_` (the shape of
--- `LUA_NVIM.md`).
---@type Rules.TocParams
M.TOC_DEFAULTS = { max = 4, base = 2, step = 2, unicode = 0, underscore = 1 }

--- Parameters that are switches, not sizes.
---@type table<string, true>
local TOC_SWITCHES = { unicode = true, underscore = true }

--- Read a `{{toc ...}}` line: `{{toc}}` or `{{toc max=2 base=0 step=2 unicode=1}}`.
---@param line string
---@return Rules.TocParams|nil params  nil when the line is no table token
---@return string|nil err  set when it is one, but a bad one
function M.parse_toc_token(line)
  local args = line:match("^{{toc%s*(.-)%s*}}$")
  if not args then
    return nil, nil
  end
  local params = vim.deepcopy(M.TOC_DEFAULTS)
  for key, value in args:gmatch("(%S+)=(%S+)") do
    local n = tonumber(value)
    local limit = TOC_SWITCHES[key] and 1 or 8
    if params[key] == nil or not n or n ~= math.floor(n) or n < 0 or n > limit then
      return nil,
        (
          "bad table of contents parameter %s=%s (want max, base, step, unicode, underscore; "
          .. "whole numbers, the last two 0 or 1)"
        ):format(key, value)
    end
    params[key] = n
  end
  if args:gsub("%S+=%S+", ""):match("%S") then
    return nil, ("bad table of contents parameters %q"):format(args)
  end
  if params.max < 2 or params.max > 6 then
    return nil, "table of contents `max` must be 2 to 6"
  end
  return params, nil
end

--- The token that gives `params` (the shortest one).
---@param params Rules.TocParams
---@return string
function M.toc_token(params)
  local parts = {}
  for _, key in ipairs({ "max", "base", "step", "unicode", "underscore" }) do
    if params[key] ~= M.TOC_DEFAULTS[key] then
      parts[#parts + 1] = ("%s=%d"):format(key, params[key])
    end
  end
  if #parts == 0 then
    return M.TOC_TOKEN
  end
  return ("{{toc %s}}"):format(table.concat(parts, " "))
end

--- The table of contents of a document: one line per heading from level 2 to
--- `params.max` (the title is not listed, nor is the heading of the table
--- itself), indented, each a link to its anchor. A second heading with the same
--- anchor gets `-1`, `-2`, ... like the renderers do.
---@param lines string[]  the document, without the table
---@param params? Rules.TocParams  default `M.TOC_DEFAULTS`
---@return string[]
function M.toc_lines(lines, params)
  params = params or M.TOC_DEFAULTS
  local out = {}
  local seen = {}
  for _, h in ipairs(headings(lines)) do
    if h.level >= 2 and h.level <= params.max and h.text:lower() ~= TOC_HEADING then
      local slug = M.slug(h.text, params)
      local count = seen[slug]
      seen[slug] = (count or 0) + 1
      if count then
        slug = ("%s-%d"):format(slug, count)
      end
      local indent = params.base + params.step * (h.level - 2)
      out[#out + 1] = ("%s- [%s](#%s)"):format((" "):rep(indent), h.text, slug)
    end
  end
  return out
end

-- ── layout ───────────────────────────────────────────────────────────────────

---@class Rules.Layout
---@field output string  path of the document, relative to the ruleset root, with `/`
---@field lines string[]  the body, one entry per line

--- Is `path` a place a layout may write to: relative, inside the root, a file name?
---@param path any
---@return boolean ok
---@return string|nil why
local function safe_output(path)
  if type(path) ~= "string" or path == "" then
    return false, "`output` must be a non-empty string"
  end
  if path:find("[%c\\]") or path:match("^/") or path:match("^%a:") or path:match("/$") then
    return false, "`output` must be a relative path with `/` that names a file"
  end
  for segment in path:gmatch("[^/]+") do
    if segment == ".." or segment == "." then
      return false, "`output` must stay inside the ruleset (no `.` or `..`)"
    end
  end
  if not path:match("%.md$") then
    return false, "`output` must end in .md"
  end
  return true, nil
end

--- Read a layout from its text.
---@param text string
---@return Rules.Layout|nil layout
---@return string|nil err
function M.parse_layout(text)
  text = text:gsub("\r\n", "\n")
  local parsed = frontmatter.parse(text)
  if not parsed or not parsed.has_block or parsed.meta.kind ~= "layout" then
    return nil, "not a layout (the frontmatter needs `kind: layout`)"
  end
  local ok, why = safe_output(parsed.meta.output)
  if not ok then
    return nil, why
  end
  local body = vim.split(parsed.body, "\n", { plain = true })
  if body[#body] == "" then
    body[#body] = nil
  end
  return { output = parsed.meta.output, lines = body }, nil
end

-- ── one rule in the document ─────────────────────────────────────────────────

--- How a rule reads in a document: the lines of its file with the ```rule
--- block (the identity lines put back in) at its place.
---@param rule_file Rules.RuleFile
---@return string[]
function M.segment_lines(rule_file)
  local lines = rule_file.lines
  local out = {}
  local function fence(rest_from, rest_to)
    out[#out + 1] = "```rule"
    out[#out + 1] = ('id = "%s",'):format(rule_file.id)
    out[#out + 1] = ('severity = "%s",'):format(rule_file.severity)
    for i = rest_from, rest_to do
      out[#out + 1] = lines[i]
    end
    out[#out + 1] = "```"
  end

  local block = rule_file.block
  if block then
    for i = 1, block.s - 1 do
      out[#out + 1] = lines[i]
    end
    fence(block.s + 1, block.e - 1)
    for i = block.e + 1, #lines do
      out[#out + 1] = lines[i]
    end
  else
    local split = parser.implicit_split(rule_file)
    for i = 1, split do
      out[#out + 1] = lines[i]
    end
    fence(1, 0)
    out[#out + 1] = ""
    for i = split + 1, #lines do
      out[#out + 1] = lines[i]
    end
  end
  return out
end

-- ── the document ─────────────────────────────────────────────────────────────

---@alias Rules.RuleFileLookup fun(id: string): Rules.RuleFile|nil, string|nil

--- Put a document together from a layout.
---@param layout Rules.Layout
---@param lookup Rules.RuleFileLookup  the rule file of an id, or `nil, why`
---@param header string|nil  first line of the output
---@return string|nil text  `"\n"` line endings, ends with a newline
---@return string[] problems  one per token that could not be filled
---@return string[] used  the ids that were put in, in order
function M.render(layout, lookup, header)
  local out = {}
  local problems = {}
  local used = {}
  local seen = {}
  local toc_at, toc_params
  if header then
    out[1] = header
  end
  for n, line in ipairs(layout.lines) do
    local id = line:match("^{{rule%s+([^%s}]+)%s*}}$")
    local params, params_err = M.parse_toc_token(line)
    if params_err then
      problems[#problems + 1] = ("layout line %d: %s"):format(n, params_err)
    elseif params then
      if toc_at then
        problems[#problems + 1] = ("layout line %d: more than one {{toc}}"):format(n)
      else
        toc_at = #out + 1
        toc_params = params
        out[toc_at] = false
      end
    elseif id then
      if seen[id] then
        problems[#problems + 1] = ("layout line %d: rule %s is placed twice"):format(n, id)
      else
        seen[id] = true
        local rule_file, why = lookup(id)
        if rule_file then
          used[#used + 1] = id
          for _, seg in ipairs(M.segment_lines(rule_file)) do
            out[#out + 1] = seg
          end
        else
          problems[#problems + 1] = ("layout line %d: rule %s: %s"):format(n, id, why or "not found")
        end
      end
    else
      out[#out + 1] = line
    end
  end
  if #problems > 0 then
    return nil, problems, used
  end
  if toc_at then
    local rest = {}
    for i, line in ipairs(out) do
      if i ~= toc_at then
        rest[#rest + 1] = line
      end
    end
    local toc = M.toc_lines(rest, toc_params)
    local with_toc = {}
    for i = 1, toc_at - 1 do
      with_toc[#with_toc + 1] = out[i]
    end
    for _, line in ipairs(toc) do
      with_toc[#with_toc + 1] = line
    end
    for i = toc_at + 1, #out do
      with_toc[#with_toc + 1] = out[i]
    end
    out = with_toc
  end
  return table.concat(out, "\n") .. "\n", {}, used
end

--- The header line of a generated document.
---@param layout_rel string  the layout's path relative to the ruleset root
---@return string
function M.header(layout_rel)
  return ("%s from %s: do not edit, change the layout and the rule files and run :Rules catalog -->"):format(
    parser.GENERATED_PREFIX,
    (layout_rel:gsub("%-%-", "- -"):gsub(">", "&gt;"))
  )
end

-- ── the disk ─────────────────────────────────────────────────────────────────

---@param path string
---@return string|nil
local function read_file(path)
  local f = io.open(path, "rb")
  if not f then
    return nil
  end
  local text = f:read("*a")
  f:close()
  return text
end

---@class Rules.CatalogResult
---@field layout string  the layout file
---@field output string  the document it makes
---@field status "written"|"unchanged"|"stale"|"error"
---@field problems string[]
---@field unused string[]|nil  rule ids that are in the ruleset but in no layout (set on the first result only)

--- Make every document of the ruleset at `root`, or with `opts.check` only say
--- which ones are not up to date. A document is written only when its content
--- changed (compared with line endings ignored; an existing CRLF file stays CRLF).
---@param root string
---@param opts? { check?: boolean }
---@return Rules.CatalogResult[] results
---@return string[] errors  problems with the ruleset itself (it did not load cleanly)
function M.build(root, opts)
  opts = opts or {}
  local base = vim.fs.normalize(vim.fn.fnamemodify(expand_path(root), ":p")):gsub("/+$", "")
  local results = {}

  local layouts = {}
  for _, file in ipairs(fswalk.files(base)) do
    if file:match("%.md$") then
      local read_ok, lines = pcall(vim.fn.readfile, file)
      if read_ok and parser.classify(lines) == "layout" then
        layouts[#layouts + 1] = file
      end
    end
  end
  table.sort(layouts)

  local rules, load_errors = loader.load({ base })
  local by_id = {}
  for _, rule in ipairs(rules) do
    by_id[rule.id] = rule
  end

  local function lookup(id)
    local rule = by_id[id]
    if not rule then
      return nil, "not loaded"
    end
    local rule_file, errs = parser.read_rule_file(rule.source_file)
    if not rule_file then
      return nil, errs[1] or "not a rule file"
    end
    return rule_file, nil
  end

  local placed = {}
  for _, layout_path in ipairs(layouts) do
    local rel = layout_path:sub(#base + 2)
    local result = { layout = layout_path, output = "", status = "error", problems = {} }
    results[#results + 1] = result
    local text = read_file(layout_path)
    local layout, why = M.parse_layout(text or "")
    if not layout then
      result.problems[1] = ("%s: %s"):format(rel, why)
    else
      result.output = base .. "/" .. layout.output
      local rendered, problems, used = M.render(layout, lookup, M.header(rel))
      for _, id in ipairs(used) do
        placed[id] = true
      end
      if not rendered then
        for _, p in ipairs(problems) do
          result.problems[#result.problems + 1] = ("%s: %s"):format(rel, p)
        end
      else
        local existing = read_file(result.output)
        local was_crlf = existing ~= nil and existing:find("\r\n", 1, true) ~= nil
        local same = existing ~= nil and existing:gsub("\r\n", "\n") == rendered
        if same then
          result.status = "unchanged"
        elseif opts.check then
          result.status = "stale"
        else
          local out_text = was_crlf and rendered:gsub("\n", "\r\n") or rendered
          local ok_write, write_err = require("lib.nvim.fs.write.atomic")(result.output, out_text, { mkdirp = true })
          if ok_write then
            result.status = "written"
          else
            result.problems[1] = ("%s: %s"):format(result.output, write_err)
          end
        end
      end
    end
  end

  local unused = {}
  for _, rule in ipairs(rules) do
    if not placed[rule.id] and parser.classify(vim.fn.readfile(rule.source_file)) == "rule" then
      unused[#unused + 1] = rule.id
    end
  end
  table.sort(unused)
  if results[1] then
    results[1].unused = unused
  end
  return results, load_errors
end

return M
