---@module 'rules.engine.parser'
---@brief Extract rules from Markdown: a rule file (frontmatter, optional ```rule block) or a document of ```rule blocks.
---@description
--- A Markdown file is one of four things, told apart by `M.classify`: a
--- catalog the generator wrote and a layout (both skipped), a **rule file**, or
--- a **document** (the legacy shape).
---
--- A rule file starts with a `---` frontmatter holding `id` and `severity` and,
--- optionally, `family`; any other key is an error. It yields exactly one rule.
--- Its ` ```rule ` block is optional: it says only what the frontmatter cannot
--- (a `check`, an `agent`) and may repeat `id`/`severity` only when they agree.
--- `title` is the heading that names the rule and `text` the prose under the
--- block (under the heading, when there is no block). `section` is never set:
--- which section a rule sits in is the business of the layout. A rule file with
--- a fault is told, never skipped silently: an unclosed frontmatter, a key it
--- does not know, a bad id are errors.
---
--- A document has no such frontmatter. There the parser looks for exactly one
--- marker: a fenced code block tagged ` ```rule `. Everything else in the file
--- — headings, prose, other fenced blocks, old table-based rule text — is
--- invisible to it on purpose. That is what keeps a format migration
--- incremental: a file half in the legacy table format and half in the new
--- fenced-block format parses correctly, picking up only the entries that have
--- actually been converted.
---
--- A block's content is a Lua table-constructor *body* (fields, not the
--- surrounding braces). Fields need the usual Lua field separator (a comma
--- or a semicolon) between them, same as any Lua table literal. It is
--- evaluated in an **empty environment** (`rules.util.sandbox`): a ruleset is
--- code, and a body that calls anything fails as a malformed block. A
--- `check.fn` survives as a closure and only gets its environment back when
--- the host trusts predicates -- see `checks/lua_predicate.lua`.
---
--- Around the block the parser keeps three things the block cannot say about
--- itself. `text` is the prose under it, up to the next heading or rule block.
--- `title` is the heading the rule sits under when that heading names the rule
--- (`#### `DEP-01` — ...`, which is how every real ruleset is written), and
--- `section` is the heading above that -- what a catalog groups by (nil for a
--- rule file). Headings inside other fenced blocks (a shell comment in a
--- ```bash example) are not headings. These three belong to the parser: a
--- block that sets a field of the same name has it overwritten, like
--- `source_file`.

local safe_error = require("lib.lua.error")
local frontmatter = require("lib.nvim.markdown.frontmatter")
local sandbox = require("rules.util.sandbox")

local M = {}

--- A Markdown file that starts with this is a reading document the catalog
--- generator wrote (`rules.engine.catalog`). It repeats rules that live in
--- their own files, so the loader skips it: loading both would make every rule
--- a duplicate.
M.GENERATED_PREFIX = "<!-- GENERATED by rules.nvim"

--- The keys a rule file's frontmatter may have. A typo (`severtiy`) is an
--- error, not an ignored key: this is the file the authoring tools write.
---@type table<string, true>
local RULE_FILE_KEYS = { id = true, severity = true, family = true }

---@class Rules.AgentSpec
---@field question string|nil  replaces the generic "does the code comply with the rule text"
---@field include string[]|nil  globs saying where an agent should look
---@field max_files integer|nil

---@class Rules.ParsedRule
---@field id string
---@field severity "critical"|"recommended"|"nice-to-have"
---@field check table|nil
---@field agent Rules.AgentSpec|nil  validated; an invalid one is dropped and reported
---@field title string|nil  the heading that names this rule
---@field section string|nil  the heading above it
---@field text string  the prose under the block, "" when there is none
---@field source_file string
---@field source_line integer

---@type table<string, true>
local VALID_SEVERITIES = { critical = true, recommended = true, ["nice-to-have"] = true }

---@type table<string, true>
local AGENT_KEYS = { question = true, include = true, max_files = true }

--- Bounds on what a block may say. A ruleset can come from a folder nobody
--- wrote by hand, and these strings end up in reports, prompts and globs: a
--- megabyte `question` or an id with a newline in it is not a rule, it is
--- something that breaks the next consumer.
local MAX_ID_BYTES = 100
local MAX_QUESTION_BYTES = 4000
local MAX_INCLUDE_ENTRIES = 50
local MAX_GLOB_BYTES = 200

--- What a rule file's `id` must be (`is_file_name`), for the message.
local ID_FILE_NAME_MESSAGE = "rule `id` must be at most %d bytes of letters, digits, `-`, `_` and `.` "
  .. "(not `..`, not at either end): it is the file name"

--- A string with no content once whitespace is gone.
---@param s any
---@return boolean
local function is_blank(s)
  return type(s) ~= "string" or s:match("^%s*$") ~= nil
end

--- Index of the last byte of `s` that is not whitespace (0 when there is none).
--- Walks back from the end, so it is linear. The obvious `(.-)%s*$` retries the
--- rest of a whitespace run from every byte inside it: 40 000 spaces in the
--- middle of a heading cost seconds (lib.nvim's frontmatter names this SEC-32).
---@param s string
---@return integer
local function last_non_space(s)
  local i = #s
  while i > 0 and s:find("^%s", i) do
    i = i - 1
  end
  return i
end

--- The level and the text of a Markdown heading line, or nil when the line is
--- none. The same reading as `^(#+)%s+(.-)%s*$`, without that pattern's
--- quadratic retry inside a long whitespace run.
---@param line string
---@return integer|nil level  the number of `#`, which may exceed 6: the caller decides
---@return string|nil text  without the `#` and the whitespace around the text
local function heading_of(line)
  local hashes, rest = line:match("^(#+)%s+(.*)$")
  if not hashes then
    return nil, nil
  end
  return #hashes, rest:sub(1, last_non_space(rest))
end

--- A value out of a rule file for use in a message: cut to the id bound and
--- with control characters made visible, so a hostile file cannot forge log
--- lines or terminal escapes through an error text.
---@param value string
---@return string
local function shown(value)
  local cut = value:sub(1, MAX_ID_BYTES):gsub("%c", "?")
  return #value > MAX_ID_BYTES and cut .. "..." or cut
end

--- Whether an id is safe to be a file name: a rule file is `<FAMILY>/<ID>.md`
--- (the migration builds that path from the id), so an id must not be able to
--- leave its folder or name something else. Letters, digits, `-`, `_` and `.`
--- only; no `..`, and no `.` at either end (a leading one hides the file,
--- Windows drops a trailing one).
---@param id string
---@return boolean
local function is_file_name(id)
  return not id:find("[^A-Za-z0-9._-]") and not id:find("..", 1, true) and id:sub(1, 1) ~= "." and id:sub(-1) ~= "."
end

--- Check a block's optional `agent` field. A bad one is dropped, not fatal: the
--- rule's mechanical check does not depend on it, so losing the whole rule
--- over a typo in an optional hint would remove it from a gate.
---@param agent any
---@return Rules.AgentSpec|nil clean  only the known, valid keys
---@return string|nil problem  why it was dropped
local function validate_agent(agent)
  if type(agent) ~= "table" or vim.islist(agent) and #agent > 0 then
    return nil, "must be a table"
  end

  for key in pairs(agent) do
    if not AGENT_KEYS[key] then
      return nil, ("unknown key %s (want question, include, max_files)"):format(tostring(key))
    end
  end

  if agent.question ~= nil and is_blank(agent.question) then
    return nil, "`question` must be a non-empty string"
  end
  if agent.question ~= nil and #agent.question > MAX_QUESTION_BYTES then
    return nil, ("`question` is longer than %d bytes"):format(MAX_QUESTION_BYTES)
  end

  if agent.include ~= nil then
    local ok = type(agent.include) == "table" and vim.islist(agent.include) and #agent.include > 0
    if ok then
      for _, glob in ipairs(agent.include) do
        if is_blank(glob) or #glob > MAX_GLOB_BYTES then
          ok = false
          break
        end
      end
    end
    if not ok then
      return nil, ("`include` must be a non-empty list of non-empty strings (each up to %d bytes)"):format(MAX_GLOB_BYTES)
    end
    if #agent.include > MAX_INCLUDE_ENTRIES then
      return nil, ("`include` has more than %d entries"):format(MAX_INCLUDE_ENTRIES)
    end
  end

  local max_files = agent.max_files
  if max_files ~= nil and (type(max_files) ~= "number" or max_files < 1 or max_files ~= math.floor(max_files)) then
    return nil, "`max_files` must be a positive integer"
  end

  return { question = agent.question, include = agent.include, max_files = max_files }, nil
end

--- Join prose lines into one string, without the blank lines and the Markdown
--- thematic breaks (`---`) that merely frame it.
---@param lines string[]
---@return string
local function prose(lines)
  local first, last = 1, #lines
  local function is_framing(line)
    local bare = line:gsub("%s", "")
    return bare == "" or bare:match("^%-%-%-+$") ~= nil or bare:match("^%*%*%*+$") ~= nil or bare:match("^___+$") ~= nil
  end
  while first <= last and is_framing(lines[first]) do
    first = first + 1
  end
  while last >= first and is_framing(lines[last]) do
    last = last - 1
  end
  return table.concat(lines, "\n", first, last)
end

--- The outline position of a rule: its own title and the section above it.
---@param stack {level: integer, text: string}[]  open headings, shallowest first
---@param id string
---@return string|nil title
---@return string|nil section
local function place(stack, id)
  local top = stack[#stack]
  if top and top.text:find(id, 1, true) then
    local parent = stack[#stack - 1]
    return top.text, parent and parent.text or nil
  end
  return nil, top and top.text or nil
end

