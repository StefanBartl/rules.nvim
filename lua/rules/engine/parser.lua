---@alias Rules.FileKind "generated"|"layout"|"rule"|"legacy"

--- A frontmatter delimiter: `---` and trailing blanks, for the opening line as
--- for the closing one (the frontmatter module's own test).
---@param line string
---@return boolean
local function is_delimiter(line)
  return line:match("^%-%-%-[ \t]*$") ~= nil
end

--- The key of a frontmatter line `key: value`, nil when the line is none (the
--- frontmatter module's reading).
---@param line string
---@return string|nil
local function key_of(line)
  local key, rest = line:match("^([%w_][%w_%.%-]*)[ \t]*:(.*)$")
  if key and (rest == "" or rest:match("^[ \t]")) then
    return key
  end
  return nil
end

--- A `---` that is never closed is a thematic break at the top of a document,
--- unless it starts like a rule file's frontmatter: `id:` or `severity:` among
--- the first lines (key lines, blanks and comments only) is a rule file whose
--- closing `---` was forgotten or mistyped (`----`, `--`), and that is a fault
--- to tell, not a document to skip.
---@param lines string[]
---@return integer|nil last  index of the line with the `id`/`severity` key, nil when this is no rule file
local function unclosed_rule_head(lines)
  for i = 2, #lines do
    local line = lines[i]
    local key = key_of(line)
    if key == "id" or key == "severity" then
      return i
    elseif not key and not is_blank(line) and not line:match("^%s*#") then
      return nil
    end
  end
  return nil
end

--- What a Markdown file is, from its first lines: a reading document the
--- catalog generator wrote (skipped), a layout (skipped), a rule file, or the
--- legacy shape (rule blocks inside a document).
---@param lines string[]
---@return Rules.FileKind kind
---@return Lib.Markdown.Frontmatter.Parsed|nil parsed  set for "layout" and "rule"; for an unclosed rule file `unterminated`
function M.classify(lines)
  local first = (lines[1] or ""):gsub("^\239\187\191", "")
  if first:sub(1, #M.GENERATED_PREFIX) == M.GENERATED_PREFIX then
    return "generated", nil
  end
  if not is_delimiter(first) then
    return "legacy", nil
  end

  -- Parse only up to the closing `---`: what follows is none of the frontmatter's business, and a large document that
  -- merely starts with a thematic break must not be read twice.
  local close
  for i = 2, #lines do
    if is_delimiter(lines[i]) then
      close = i
      break
    end
  end
  if not close then
    local head = unclosed_rule_head(lines)
    local unclosed = head and frontmatter.parse(table.concat(lines, "\n", 1, head))
    if unclosed then
      return "rule", unclosed
    end
    return "legacy", nil
  end
  local parsed = frontmatter.parse(table.concat(lines, "\n", 1, close))
  if not parsed or not parsed.has_block or parsed.prose then
    return "legacy", nil
  end
  if parsed.meta.kind == "layout" then
    return "layout", parsed
  end
  -- `id` or `severity` is what makes it a rule file; one without the other is a rule file with a fault, which is
  -- told, not a document that happens to start with a frontmatter
  for _, key in ipairs({ "id", "severity" }) do
    if parsed.meta[key] ~= nil or parsed.opaque[key] ~= nil then
      return "rule", parsed
    end
  end
  return "legacy", nil
end

---@class Rules.RuleFile
---@field id string
---@field severity string
---@field family string|nil  the frontmatter's `family`, when it has one
---@field lines string[]  the body: everything after the frontmatter and the one blank line that follows it
---@field offset integer  file line number of `lines[1]`, minus one
---@field heading integer|nil  index in `lines` of the heading that names the rule, outside a fence: the nearest above the
---   ```rule block, or the first one when there is no block
---@field block {s: integer, e: integer, fence: integer}|nil  indexes in `lines` of the opening and closing fence of the
---   ```rule block, and the length of the fence it sits in (0 for none)

--- The family of a rule id, as `rules.engine.runner.family_of` defines it and
--- `:Rules check --family=` and the gates match it: the leading letters when a
--- `-` follows them (`DEP` for `DEP-06`), else the whole id (`DEP2-01` and
--- `DEP01` are families of their own). A frontmatter `family` must say exactly
--- this. The runner pulls in the checks, so the definition is repeated here;
--- a spec holds the two together.
---@param id string
---@return string
function M.family_of(id)
  return id:match("^(%a+)%-") or id
end

--- Split one rule file into the parts the loader and the catalog generator
--- both need. Checks the frontmatter (the keys, the id, the severity, the
--- family) and that there is at most one rule block. Every fault names the
--- file line it sits on.
---@param file_path string
---@param lines string[]
---@param parsed Lib.Markdown.Frontmatter.Parsed
---@return Rules.RuleFile|nil rule_file
---@return string[] errors
local function split_rule_file(file_path, lines, parsed)
  local errors = {}
  local function fail(line, message)
    errors[#errors + 1] = ("%s:%d: %s"):format(file_path, line, message)
  end

  -- `readfile` hands a NUL byte over as a newline inside the line: the lines of the file and those of the frontmatter
  -- parser would no longer be the same lines, and the body would start in the wrong place
  for i, line in ipairs(lines) do
    if line:find("\n", 1, true) then
      fail(i, "the file contains a NUL byte")
      return nil, errors
    end
  end
  if parsed.unterminated then
    fail(1, "frontmatter is not closed by a second `---` line")
    return nil, errors
  end

  local key_line = {}
  for _, entry in ipairs(parsed.entries) do
    if entry.key then
      key_line[entry.key] = entry.line
    end
  end
  --- the file line of a key (its last one), 1 when the key is missing
  local function line_of(key)
    return key_line[key] or 1
  end

  for _, key in ipairs(parsed.order) do
    if not RULE_FILE_KEYS[key] then
      fail(line_of(key), ("unknown frontmatter key `%s` (want id, severity, family)"):format(key))
    end
  end
  -- a duplicate or a line that is no `key: value` would be dropped silently by the frontmatter reader (the last
  -- duplicate wins): there is no silent choice in a rule file
  local seen = {}
  for _, entry in ipairs(parsed.entries) do
    if entry.key and entry.opaque then
      fail(entry.line, ("frontmatter key `%s` is not understood (%s)"):format(entry.key, entry.opaque))
    elseif entry.key then
      if seen[entry.key] then
        fail(entry.line, ("frontmatter key `%s` appears more than once"):format(entry.key))
      end
      seen[entry.key] = true
    end
  end
  for _, warning in ipairs(parsed.warnings) do
    local stray = warning:match("^line (%d+): not a `key: value` line")
    if stray then
      fail(tonumber(stray), "frontmatter line is not a `key: value` line")
    end
  end

  local id, severity, family = parsed.meta.id, parsed.meta.severity, parsed.meta.family
  -- a bad id stops here: it is not repeated in the messages below (it may be megabytes of control characters)
  if type(id) ~= "string" or id == "" then
    fail(line_of("id"), "rule file has no string `id` in its frontmatter")
    return nil, errors
  elseif #id > MAX_ID_BYTES or not is_file_name(id) then
    fail(line_of("id"), ID_FILE_NAME_MESSAGE:format(MAX_ID_BYTES))
    return nil, errors
  end
  if type(severity) ~= "string" then
    fail(line_of("severity"), ("rule %s has no string `severity` in its frontmatter"):format(id))
  elseif not VALID_SEVERITIES[severity] then
    fail(
      line_of("severity"),
      ('rule %s has invalid `severity` "%s" (want critical/recommended/nice-to-have)'):format(id, shown(severity))
    )
  end
  if family ~= nil then
    if type(family) ~= "string" then
      fail(line_of("family"), ("rule %s: `family` must be a string"):format(id))
    elseif family ~= M.family_of(id) then
      fail(
        line_of("family"),
        ("rule %s: `family` %s does not match the id's family %s"):format(id, shown(family), M.family_of(id))
      )
    end
  end
  if #errors > 0 then
    return nil, errors
  end

  -- the body starts after the closing `---`, minus one blank separator line
  local body_from = #parsed.raw_lines + 3
  if (lines[body_from] or "") == "" and lines[body_from + 1] ~= nil then
    body_from = body_from + 1
  end
  local body = {}
  for i = body_from, #lines do
    body[#body + 1] = lines[i]
  end

  local rule_file = {
    id = id,
    severity = severity,
    family = family,
    lines = body,
    offset = body_from - 1,
  }

  -- the headings above the rule block (outside a fence), and the (one) rule block; like the legacy scanner, the block
  -- is found by its opening line whatever fence is open, and the fence it sits in is kept for the prose scan below it
  local fence = 0
  local first_heading, last_heading
  for i, line in ipairs(body) do
    if line:match("^```rule%s*$") then
      local close
      for j = i + 1, #body do
        if body[j]:match("^```%s*$") then
          close = j
          break
        end
      end
      if close then
        rule_file.block = { s = i, e = close, fence = fence }
        for j = close + 1, #body do
          if body[j]:match("^```rule%s*$") then
            fail(rule_file.offset + j, ("rule file for %s has more than one ```rule block"):format(id))
            break
          end
        end
      else
        fail(rule_file.offset + i, "unterminated ```rule block")
      end
      break
    elseif fence > 0 then
      local ticks = line:match("^(`+)%s*$")
      if ticks and #ticks >= fence then
        fence = 0
      end
    elseif line:match("^```") then
      fence = #line:match("^(`+)")
    elseif line:match("^#+%s+%S") then
      first_heading = first_heading or i
      last_heading = i
    end
  end
  -- with a block the rule sits under the nearest heading above it (as in a document); without one, under the first
  rule_file.heading = rule_file.block and last_heading or first_heading
  if #errors > 0 then
    return nil, errors
  end
  return rule_file, {}
end

--- Split the text of a rule file (the catalog generator and the migration
--- check work on texts that are not on disk yet).
---@param file_path string  only for messages
---@param text string
---@return Rules.RuleFile|nil rule_file
---@return string[] errors
function M.split_text(file_path, text)
  local lines = vim.split(text, "\n", { plain = true })
  if lines[#lines] == "" then
    lines[#lines] = nil
  end
  local kind, parsed = M.classify(lines)
  if kind ~= "rule" or not parsed then
    return nil, { ("%s: not a rule file"):format(file_path) }
  end
  return split_rule_file(file_path, lines, parsed)
end

--- Read and split one rule file; for the catalog generator.
---@param file_path string
---@return Rules.RuleFile|nil rule_file
---@return string[] errors
function M.read_rule_file(file_path)
  local read_ok, lines = safe_error.safe_call(vim.fn.readfile, file_path)
  if not read_ok then
    return nil, { ("%s: could not read (%s)"):format(file_path, lines.message) }
  end
  local kind, parsed = M.classify(lines)
  if kind ~= "rule" or not parsed then
    return nil, { ("%s: not a rule file"):format(file_path) }
  end
  return split_rule_file(file_path, lines, parsed)
end

--- Where the implicit rule block of a file that has none sits: after the first
--- heading and the blank lines under it (0 without a heading).
---@param rule_file Rules.RuleFile
---@return integer split  index in `lines` of the last line before the block
function M.implicit_split(rule_file)
  local split = rule_file.heading or 0
  while (rule_file.lines[split + 1] or "x") == "" do
    split = split + 1
  end
  return split
end

--- The rule a rule file stands for: the block (if any) plus what the
--- frontmatter and the Markdown around it say.
---@param file_path string
---@param rule_file Rules.RuleFile
---@return Rules.ParsedRule|nil rule
---@return string[] errors
local function rule_from_file(file_path, rule_file)
  local errors = {}
  local function fail(line, message)
    errors[#errors + 1] = ("%s:%d: %s"):format(file_path, line, message)
  end

  local rule = {}
  local block = rule_file.block
  local source_line
  if block then
    local src = table.concat(rule_file.lines, "\n", block.s + 1, block.e - 1)
    local line = rule_file.offset + block.s
    local evaluated, eval_err = sandbox.eval_table(src, "rule@" .. file_path .. ":" .. line)
    if not evaluated then
      fail(line, eval_err)
      return nil, errors
    end
    rule = evaluated
    -- one truth for id and severity: the frontmatter; a block that repeats
    -- them must agree, there is no silent choice
    if rule.id ~= nil and rule.id ~= rule_file.id then
      fail(line, ("rule block `id` %s differs from the frontmatter `id` %s"):format(tostring(rule.id), rule_file.id))
    end
    if rule.severity ~= nil and rule.severity ~= rule_file.severity then
      fail(
        line,
        ("rule %s: block `severity` %s differs from the frontmatter `severity` %s"):format(
          rule_file.id,
          tostring(rule.severity),
          rule_file.severity
        )
      )
    end
    if #errors > 0 then
      return nil, errors
    end
    source_line = line
  else
    source_line = rule_file.offset + (rule_file.heading or 1)
  end

  rule.id = rule_file.id
  rule.severity = rule_file.severity
  if rule.agent ~= nil then
    local clean, problem = validate_agent(rule.agent)
    if not clean then
      fail(source_line, ("rule %s: invalid `agent` field (%s) -- ignored"):format(rule.id, problem))
    end
    rule.agent = clean
  end

  -- title: the heading that names the rule; section belongs to the layout
  rule.title = nil
  if rule_file.heading then
    local _, heading = heading_of(rule_file.lines[rule_file.heading])
    if heading and heading:find(rule.id, 1, true) then
      rule.title = heading
    end
  end
  rule.section = nil

  -- text: the prose under the block (or, with none, under the heading and its
  -- blank lines), up to the next heading outside a fence
  local from = block and (block.e + 1) or (M.implicit_split(rule_file) + 1)
  local text_lines = {}
  -- a block inside a longer fence (a ````markdown example) leaves that fence open: its closing line is not an opening one
  local fence = block and block.fence or 0
  for i = from, #rule_file.lines do
    local line = rule_file.lines[i]
    if fence > 0 then
      local ticks = line:match("^(`+)%s*$")
      if ticks and #ticks >= fence then
        fence = 0
      end
      text_lines[#text_lines + 1] = line
    elseif line:match("^```") then
      fence = #line:match("^(`+)")
      text_lines[#text_lines + 1] = line
    elseif (heading_of(line) or 7) <= 6 then
      break
    else
      text_lines[#text_lines + 1] = line
    end
  end
  rule.text = prose(text_lines)
  rule.source_file = file_path
  rule.source_line = source_line
  return rule, errors
end

--- Extract the fenced ```rule blocks from one Markdown file, or the one rule
--- of a rule file (frontmatter `id`/`severity`). A catalog the generator wrote
--- and a layout yield nothing.
---@param file_path string
---@return Rules.ParsedRule[] rules
---@return string[] errors  one entry per block that failed to parse
function M.extract_rules(file_path)
  local rules = {}
  local errors = {}

  if vim.fn.filereadable(file_path) == 0 then
    errors[#errors + 1] = ("%s: not readable"):format(file_path)
    return rules, errors
  end

  -- ERR-01: `filereadable` above only checks openability at that instant --
  -- a TOCTOU window (the file removed/renamed/locked before this read) means
  -- `readfile` can still throw (`E484`) rather than return an error value.
  local read_ok, lines = safe_error.safe_call(vim.fn.readfile, file_path)
  if not read_ok then
    errors[#errors + 1] = ("%s: could not read (%s)"):format(file_path, lines.message)
    return rules, errors
  end

  local kind, parsed = M.classify(lines)
  if kind == "generated" or kind == "layout" then
    return rules, errors
  elseif kind == "rule" and parsed then
    local rule_file, split_errors = split_rule_file(file_path, lines, parsed)
    vim.list_extend(errors, split_errors)
    if rule_file then
      local rule, rule_errors = rule_from_file(file_path, rule_file)
      vim.list_extend(errors, rule_errors)
      if rule then
        rules[1] = rule
      end
    end
    return rules, errors
  end

  local in_block = false
  local block_start = nil
  local block_lines = {}

  -- Outline and prose tracking. `fence` is the backtick count of any *other*
  -- open fenced block (0 = none), so a `# comment` inside a shell example is
  -- not mistaken for a heading. A fence closes only on at least as many
  -- backticks, which is what lets a ````markdown block show a ```rule one.
  -- `outer_fence` holds the surrounding fence while a rule block inside it is
  -- read (block detection itself does not care about fences, as it never did).
  local fence = 0
  local outer_fence = 0
  local stack = {}
  ---@type Rules.ParsedRule|nil
  local current = nil
  local text_lines = {}

  local function finish_text()
    if current then
      current.text = prose(text_lines)
    end
    current = nil
    text_lines = {}
  end

  for i, line in ipairs(lines) do
    if not in_block then
      if line:match("^```rule%s*$") then
        finish_text()
        in_block = true
        outer_fence, fence = fence, 0
        block_start = i
        block_lines = {}
      elseif fence > 0 then
        local ticks = line:match("^(`+)%s*$")
        if ticks and #ticks >= fence then
          fence = 0
        end
        text_lines[#text_lines + 1] = line
      elseif line:match("^```") then
        fence = #line:match("^(`+)")
        text_lines[#text_lines + 1] = line
      else
        local level, title = heading_of(line)
        if level and level <= 6 then
          finish_text()
          while #stack > 0 and stack[#stack].level >= level do
            stack[#stack] = nil
          end
          stack[#stack + 1] = { level = level, text = title }
        else
          text_lines[#text_lines + 1] = line
        end
      end
    else
      if line:match("^```%s*$") then
        in_block = false
        fence, outer_fence = outer_fence, 0
        local src = table.concat(block_lines, "\n")
        local rule, eval_err = sandbox.eval_table(src, "rule@" .. file_path .. ":" .. block_start)
        if not rule then
          errors[#errors + 1] = ("%s:%d: %s"):format(file_path, block_start, eval_err)
        elseif type(rule.id) ~= "string" or rule.id == "" then
          errors[#errors + 1] = ("%s:%d: rule block has no string `id`"):format(file_path, block_start)
        elseif #rule.id > MAX_ID_BYTES or rule.id:find("%c") then
          errors[#errors + 1] = ("%s:%d: rule `id` must be at most %d bytes with no control characters"):format(
            file_path,
            block_start,
            MAX_ID_BYTES
          )
        elseif type(rule.severity) ~= "string" then
          errors[#errors + 1] = ("%s:%d: rule %s has no string `severity`"):format(file_path, block_start, rule.id)
        elseif not VALID_SEVERITIES[rule.severity] then
          errors[#errors + 1] = ("%s:%d: rule %s has invalid `severity` %q (want critical/recommended/nice-to-have)"):format(
            file_path,
            block_start,
            rule.id,
            rule.severity
          )
        else
          if rule.agent ~= nil then
            local clean, problem = validate_agent(rule.agent)
            if not clean then
              errors[#errors + 1] = ("%s:%d: rule %s: invalid `agent` field (%s) -- ignored"):format(
                file_path,
                block_start,
                rule.id,
                problem
              )
            end
            rule.agent = clean
          end
          rule.title, rule.section = place(stack, rule.id)
          rule.text = ""
          rule.source_file = file_path
          rule.source_line = block_start
          rules[#rules + 1] = rule
          current = rule
        end
      else
        block_lines[#block_lines + 1] = line
      end
    end
  end

  if in_block then
    errors[#errors + 1] = ("%s:%d: unterminated ```rule block"):format(file_path, block_start)
  end
  finish_text()

  return rules, errors
end

return M
